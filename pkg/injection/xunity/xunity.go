package xunity

// XUnity.AutoTranslator deploy layer for Unity games.
//
// XUnity reads manual translation files from
//   <game>/BepInEx/Translation/<Language>/Text/*.txt   ("source=target" lines)
// at runtime, so a deploy is just: write that file + make sure the config
// selects the language. Installing the BepInEx/XUnity binaries themselves is
// deliberately out of scope here (version churn, per-game arch) — Deploy
// errors with the exact download URLs when the plugin is not installed.
//
// ponytail: no plugin download/install automation; add if a game needs it.

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"lingo-translate/pkg/model"
)

type DeployOptions struct {
	LanguageName string // display folder name, e.g. "th" or "Thai" — XUnity is case-sensitive on the folder
}

// Deploy writes the XUnity translation file into the game's BepInEx tree.
func Deploy(gamePath string, entries []model.TextEntry, opts DeployOptions) error {
	lang := strings.ToLower(strings.TrimSpace(opts.LanguageName))
	if lang == "" || lang == "thai" {
		lang = "th" // XUnity folders are ISO codes in practice; "Thai" lowercase never matches
	}
	langDir := filepath.Join(gamePath, "BepInEx", "Translation", lang, "Text")

	cfgPath := filepath.Join(gamePath, "BepInEx", "config", "XUnity.AutoTranslator.cfg")
	if _, err := os.Stat(filepath.Join(gamePath, "BepInEx", "plugins")); err != nil {
		return fmt.Errorf("BepInEx not installed in game (no BepInEx/plugins dir): download BepInEx x64 (https://github.com/BepInEx/BepInEx/releases) and XUnity.AutoTranslator (https://github.com/bbepis/XUnity.AutoTranslator/releases), extract into the game root, then re-run deploy")
	}
	if _, err := os.Stat(cfgPath); err != nil {
		// plugin may still be installed under a different config; warn but continue
		fmt.Println("[xunity] note: no XUnity.AutoTranslator.cfg yet — it is created on first game launch; verify the XUnity dll is in BepInEx/plugins")
	}

	if err := os.MkdirAll(langDir, 0755); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Auto-generated by Lingo for XUnity.AutoTranslator\n\n")
	n := 0
	for _, e := range entries {
		if e.Target == "" || e.Target == e.Source {
			continue
		}
		src := strings.ReplaceAll(e.Source, "\n", "\\n")
		tgt := strings.ReplaceAll(e.Target, "\n", "\\n")
		b.WriteString(src + "=" + tgt + "\n")
		n++
	}
	out := filepath.Join(langDir, "lingo_translations.txt")
	if err := os.WriteFile(out, []byte(b.String()), 0644); err != nil {
		return err
	}
	if err := syncCfgLanguage(cfgPath, lang); err != nil {
		return fmt.Errorf("wrote %s but could not sync Language=%s in %s: %w", out, lang, cfgPath, err)
	}
	fmt.Printf("[xunity] wrote %d translations -> %s\n", n, out)
	fmt.Printf("[xunity] Language=%s (folder and config kept in sync; XUnity ignores files under any other name)\n", lang)
	return nil
}

// syncCfgLanguage points the plugin's Language at the folder we just wrote —
// the folder name and the config value must match exactly or XUnity never
// loads the file. In-game language switching rewrites this line later; a
// redeploy re-points it at our layer.
func syncCfgLanguage(cfgPath, lang string) error {
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		if os.IsNotExist(err) {
			fmt.Println("[xunity] note: no XUnity.AutoTranslator.cfg yet — it is created on first game launch; XUnity's default Language will not match this deploy until the in-game language is switched or the cfg is edited")
			return nil
		}
		return err
	}
	lines := strings.Split(string(data), "\n")
	found := false
	for i, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "Language=") {
			lines[i] = "Language=" + lang
			found = true
			break
		}
	}
	if !found {
		lines = append(lines, "Language="+lang)
	}
	return os.WriteFile(cfgPath, []byte(strings.Join(lines, "\n")), 0644)
}
